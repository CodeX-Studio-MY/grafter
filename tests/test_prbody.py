from typing import Any

import pytest

from grafter.charter import ChangeType
from grafter.engines.base import Task
from grafter.guard import Tier
from grafter.prbody import FINGERPRINT_MARKER, LABEL_COLORS, PullRequestDraft, render_pr

FP = "0123456789abcdef"
TASK = Task(
    id="t-42",
    repo="api",
    change_type=ChangeType.TEST,
    charter_ref="goals.reliability",
    instruction="Add tests for invoice rounding",
)


def render(**overrides: Any) -> PullRequestDraft:
    args: dict[str, Any] = {
        "task": TASK,
        "tier": Tier.APPROVE,
        "summary": "Add tests for invoice rounding\n\nCovers half-up and negative totals.",
        "tests_summary": "42 passed, 0 failed",
        "coverage_before": 61.25,
        "coverage_after": 64.5,
        "risks": ["Relies on fixed exchange rate fixture"],
        "tokens": 12345,
        "cost_usd": 0.4167,
        "fingerprint": FP,
    }
    args.update(overrides)
    return render_pr(**args)


def test_title() -> None:
    assert render().title == "[grafter] test: Add tests for invoice rounding"


def test_title_truncated_to_72() -> None:
    d = render(summary="x" * 200)
    assert len(d.title) == 72
    assert d.title.startswith("[grafter] test: xxx")
    assert d.title.endswith("…")


def test_title_falls_back_to_instruction() -> None:
    assert render(summary="  \n").title == "[grafter] test: Add tests for invoice rounding"


def test_labels() -> None:
    assert render().labels == ["grafter", "tier-1", "type-test"]
    d = render(task=Task("t", "api", ChangeType.DEPENDENCY, "c", "i"), tier=Tier.AUTO)
    assert d.labels == ["grafter", "tier-0", "type-dependency"]
    assert set(d.labels) <= set(LABEL_COLORS)


def test_label_colors_cover_all_tiers_and_types() -> None:
    expected = {"grafter"} | {f"tier-{t.value}" for t in Tier}
    expected |= {f"type-{c.value}" for c in ChangeType}
    assert set(LABEL_COLORS) == expected
    assert all(len(c) == 6 and int(c, 16) >= 0 for c in LABEL_COLORS.values())


def test_body_sections_in_order() -> None:
    body = render().body
    heads = ["## Why", "## What", "## Tier", "## Tests", "## Risks", "## Cost"]
    positions = [body.index(h) for h in heads]
    assert positions == sorted(positions)


def test_body_content() -> None:
    body = render().body
    assert "goals.reliability" in body
    assert "t-42" in body
    assert "Covers half-up and negative totals." in body
    assert "Tier 1" in body and "human approval" in body
    assert "42 passed, 0 failed" in body
    assert "61.2% → 64.5% (+3.2 pp)" in body or "61.3% → 64.5% (+3.2 pp)" in body
    assert "- Relies on fixed exchange rate fixture" in body
    assert "12,345" in body and "$0.42" in body


def test_body_footer() -> None:
    lines = render().body.rstrip("\n").splitlines()
    assert lines[-2] == FINGERPRINT_MARKER.format(fp=FP)
    assert lines[-1] == "Generated by Grafter. Merge only after human review."


@pytest.mark.parametrize(
    ("before", "after", "expected"),
    [
        (70.0, 65.0, "70.0% → 65.0% (-5.0 pp)"),
        (70.0, 70.0, "70.0% → 70.0% (+0.0 pp)"),
        (None, 65.0, "n/a → 65.0%"),
        (70.0, None, "70.0% → n/a"),
        (None, None, "not measured"),
    ],
)
def test_coverage_formats(before: float | None, after: float | None, expected: str) -> None:
    assert f"Coverage: {expected}" in render(coverage_before=before, coverage_after=after).body


def test_no_risks() -> None:
    assert "None identified." in render(risks=[]).body


@pytest.mark.parametrize("tier", list(Tier))
def test_every_tier_has_meaning(tier: Tier) -> None:
    body = render(tier=tier).body
    assert f"Tier {tier.value} ({tier.name.title()})" in body


def test_marker_spoof_stripped() -> None:
    spoof = FINGERPRINT_MARKER.format(fp="feedfacefeedface")
    d = render(
        summary=f"Fix {spoof} thing",
        risks=[f"risk {spoof}", "<!--grafter:fingerprint=feedfacefeedface-->"],
        tests_summary=f"ok {spoof}",
    )
    assert "feedfacefeedface" not in d.body
    assert "feedfacefeedface" not in d.title
    assert d.body.count("grafter:fingerprint") == 1


def test_unterminated_marker_neutralised() -> None:
    d = render(summary="Fix <!-- grafter:fingerprint=feedfacefeedface", risks=["-->"])
    assert d.body.count("grafter:fingerprint") == 1


@pytest.mark.parametrize("fp", ["", "abc -->", "a b", "x" * 65])
def test_rejects_bad_fingerprint(fp: str) -> None:
    with pytest.raises(ValueError, match="fingerprint"):
        render(fingerprint=fp)
