"""Pull request title, body and labels for one Grafter change."""

from __future__ import annotations

import hashlib
import re
from dataclasses import dataclass, field

from grafter.charter import ChangeType
from grafter.engines.base import Task
from grafter.guard import Tier

# Hidden line in every Grafter PR body; `GitHubClient.find_open_pr` matches it so a rerun
# never opens a second PR for the same change.
FINGERPRINT_MARKER = "<!-- grafter:fingerprint={fp} -->"
FOOTER = "Generated by Grafter. Merge only after human review."
TITLE_MAX = 72

TIER_MEANING = {
    Tier.AUTO: "patch-level dependency bump; may auto-merge once all gates pass (opt-in).",
    Tier.APPROVE: "one-click human approval.",
    Tier.REVIEW: "full human review required.",
}

LABEL_COLORS: dict[str, str] = {
    "grafter": "5319e7",
    "tier-0": "0e8a16",
    "tier-1": "fbca04",
    "tier-2": "d93f0b",
    **{f"type-{c.value}": "c5def5" for c in ChangeType},
}

_FP_RE = re.compile(r"[A-Za-z0-9_-]{1,64}")
_MARKER_RE = re.compile(r"<!--\s*grafter:fingerprint=.*?-->", re.IGNORECASE | re.DOTALL)
_MARKER_KEY_RE = re.compile(r"grafter:fingerprint", re.IGNORECASE)


@dataclass(frozen=True)
class PullRequestDraft:
    title: str
    body: str
    labels: list[str] = field(default_factory=list)


def fingerprint_for(task: Task, target: str) -> str:
    """Stable id of a change: same repo, change type and target -> same fingerprint,
    whatever the task id or wording, so reruns find the PR already open."""
    key = f"{task.repo}|{task.change_type.value}|{target}"
    return hashlib.sha256(key.encode()).hexdigest()[:16]


def marker(fingerprint: str) -> str:
    """The exact marker line for `fingerprint`; ValueError if it could break out of it."""
    if not _FP_RE.fullmatch(fingerprint):
        raise ValueError(f"invalid fingerprint: {fingerprint!r}")
    return FINGERPRINT_MARKER.format(fp=fingerprint)


def _clean(text: str) -> str:
    """Remove fingerprint markers so model-written text cannot spoof another change's."""
    text = _MARKER_RE.sub("", text)
    return _MARKER_KEY_RE.sub("grafter-fingerprint", text)


def _coverage(before: float | None, after: float | None) -> str:
    if before is None and after is None:
        return "not measured"
    if before is None or after is None:
        b = "n/a" if before is None else f"{before:.1f}%"
        a = "n/a" if after is None else f"{after:.1f}%"
        return f"{b} → {a}"
    return f"{before:.1f}% → {after:.1f}% ({after - before:+.1f} pp)"


def _title(change_type: ChangeType, summary: str, fallback: str) -> str:
    first = next((ln.strip() for ln in summary.splitlines() if ln.strip()), "")
    if not first:
        first = next((ln.strip() for ln in fallback.splitlines() if ln.strip()), "change")
    title = f"[grafter] {change_type.value}: {first}"
    if len(title) > TITLE_MAX:
        title = title[: TITLE_MAX - 1].rstrip() + "…"
    return title


def render_pr(
    task: Task,
    tier: Tier,
    summary: str,
    tests_summary: str,
    coverage_before: float | None,
    coverage_after: float | None,
    risks: list[str],
    tokens: int,
    cost_usd: float,
    fingerprint: str,
) -> PullRequestDraft:
    footer_marker = marker(fingerprint)
    summary = _clean(summary).strip()
    instruction = _clean(task.instruction).strip()
    risk_lines = [f"- {r}" for r in (_clean(r).strip() for r in risks) if r]
    body = "\n".join(
        [
            "## Why",
            f"Charter: `{_clean(task.charter_ref).strip()}`",
            f"Task: `{_clean(task.id)}` in repo `{_clean(task.repo)}`",
            "",
            "## What",
            summary or instruction,
            "",
            "## Tier",
            f"Tier {tier.value} ({tier.name.title()}): {TIER_MEANING[tier]}",
            "",
            "## Tests",
            _clean(tests_summary).strip() or "No test summary.",
            f"Coverage: {_coverage(coverage_before, coverage_after)}",
            "",
            "## Risks",
            *(risk_lines or ["None identified."]),
            "",
            "## Cost",
            f"Tokens: {tokens:,} · Cost: ${cost_usd:.2f}",
            "",
            "---",
            footer_marker,
            FOOTER,
            "",
        ]
    )
    labels = ["grafter", f"tier-{tier.value}", f"type-{task.change_type.value}"]
    return PullRequestDraft(_title(task.change_type, summary, instruction), body, labels)
